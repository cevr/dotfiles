// The page's data on disk: `data.js`, the one file the prototype page (r3) loads, as `window.DIGEST3 = {...}`. It is
// written whole to a file beside it and renamed over it, so a page that loads it mid-write reads the old one or the
// new one, never half of either.
import { rename, writeFile } from "node:fs/promises"
import { Effect } from "effect"
import { DigestUnwritable } from "../service.ts"

/** The file's text: the page's global over `json`. */
export const dataJs = (json: string): string => `// Generated by digest export; do not edit.\nwindow.DIGEST3 = ${json}\n`

/** The sibling `path` is written as before its rename: `.<name>.next` in its folder. */
export const nextOf = (path: string): string => {
  const at = path.lastIndexOf("/") + 1
  return `${path.slice(0, at)}.${path.slice(at)}.next`
}

/** Write `text` to `path` by a rename of a sibling file. */
export const writeByRename = (path: string, text: string) =>
  Effect.tryPromise({
    try: () => writeFile(nextOf(path), text, "utf8").then(() => rename(nextOf(path), path)),
    catch: (cause) => new DigestUnwritable({ message: String(cause) }),
  })
